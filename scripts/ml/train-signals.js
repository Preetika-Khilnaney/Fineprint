#!/usr/bin/env node
// Trains one binary Naive Bayes detector per risk signal on CUAD sentences and tunes its threshold.
//   npm run train:signals
// Positives: sentences overlapping a CUAD span of the mapped category. Negatives: all other sentences.
// Thresholds are chosen on VAL (objective = mean of contract-level F1 and span-level F1, subject to
// contract precision ≥ 0.6 and sentence precision ≥ 0.3); the detector
// fires when the calibrated pattern matches OR the model probability reaches the threshold.
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {loadSplit, sentenceUnits, ROOT, fnv} from '../lib/datasets.js';
import {binary} from '../lib/metrics.js';
import {train, predict} from '../../src/engine/ml/naiveBayes.js';
import {hasSignal} from '../../src/engine/signals.js';
import {SIGNAL_TO_CUAD} from '../../src/engine/ml/cuadMapping.js';

const ov = (a, b) => Math.max(0, Math.min(a.end, b.end) - Math.max(a.start, b.start));
const prep = split => loadSplit(split).map(c => ({c, sents: sentenceUnits(c.text)}));
const TR = prep('train'), VA = prep('val');

function score(data, id, cat, fire) {
  const g = [], p = []; let spans = 0, hit = 0, fired = 0, ok = 0;
  for (const {c, sents} of data) {
    const sp = c.annotations.filter(a => a.cuad === cat);
    const f = sents.filter(s => fire(s.text));
    g.push(c.present.includes(cat)); p.push(f.length > 0);
    spans += sp.length; hit += sp.filter(a => f.some(s => ov(s, a) > 0)).length;
    fired += f.length; ok += f.filter(s => sp.some(a => ov(s, a) > 0)).length;
  }
  const b = binary(g, p), sr = spans ? hit / spans : 0, spp = fired ? ok / fired : 0, sf = sr + spp ? 2 * sr * spp / (sr + spp) : 0;
  return {contract: b, span: {recall: sr, precision: spp, f1: sf}, objective: (b.f1 + sf) / 2};
}

const out = {}, t0 = Date.now();
for (const [id, cat] of Object.entries(SIGNAL_TO_CUAD)) {
  const items = [];
  for (const {c, sents} of TR) {
    const sp = c.annotations.filter(a => a.cuad === cat);
    for (const s of sents) {
      const pos = sp.some(a => ov(s, a) >= Math.min(20, a.end - a.start));
      if (pos || fnv(c.id + s.start) % 4 === 0) items.push({text: s.text, label: pos ? 'pos' : 'neg'});   // keep 25% of negatives
    }
  }
  const m = train(items, {alpha: 1, maxFeatures: 800, minDf: 3});
  const base = score(VA, id, cat, t => !!hasSignal(id, t));
  let best = {t: null, ...base};
  for (const t of [0.5, 0.7, 0.8, 0.9, 0.95, 0.98, 0.99, 0.995]) {
    const r = score(VA, id, cat, s => !!hasSignal(id, s) || predict(m, s).probs.pos >= t);
    // Precision floor: a detector that fires on most contracts is not useful to a reviewer.
    if (r.contract.precision >= 0.6 && r.span.precision >= 0.3 && r.objective > best.objective + 0.005) best = {t, ...r};
  }
  out[id] = {threshold: best.t, model: best.t === null ? null : {labels: m.labels, logPrior: m.logPrior, vocab: m.vocab, logp: m.logp}};
  console.log(`${id.padEnd(24)} val pattern-only ${base.objective.toFixed(3)} → ${best.t === null ? 'pattern only' : 'pattern+model t=' + best.t} ${best.objective.toFixed(3)} (contract F1 ${best.contract.f1.toFixed(2)}, span F1 ${best.span.f1.toFixed(2)})`);
}
const js = `// Generated by scripts/ml/train-signals.js — do not edit by hand.\n// Binary Naive Bayes risk-signal detectors trained on CUAD v1 sentences (CC BY 4.0).\nexport default ${JSON.stringify(out)};\n`;
writeFileSync(join(ROOT, 'src', 'engine', 'ml', 'signalModels.js'), js);
console.log(`wrote src/engine/ml/signalModels.js (${(js.length / 1024).toFixed(0)} KB) in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
