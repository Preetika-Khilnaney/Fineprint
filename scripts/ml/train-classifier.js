#!/usr/bin/env node
// Trains the clause classifier on CUAD and tunes the rule/model blend on the validation split.
//   npm run train
// Protocol: hyper-parameters and blend weight are selected on VAL only; the final model is refit on
// TRAIN+VAL with those settings. The TEST split is never touched here (see scripts/eval/run-eval.js).
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {loadSplit, classificationItems, ROOT} from '../lib/datasets.js';
import {report} from '../lib/metrics.js';
import {train} from '../../src/engine/ml/naiveBayes.js';
import {classifyText} from '../../src/engine/classifier.js';
import {EVAL_LABELS, projectToEval} from '../../src/engine/ml/cuadMapping.js';

const t0 = Date.now();
const tr = classificationItems(loadSplit('train')), va = classificationItems(loadSplit('val'));
console.log(`train items ${tr.items.length} (excluded: ${JSON.stringify(tr.stats)}) · val items ${va.items.length}`);
const gold = va.items.map(i => i.label);
const score = (model, mode, w, tau) => report(gold, va.items.map(i => projectToEval(classifyText(i.text, '', {model, mode, w, tau}).cat)), EVAL_LABELS).macro.f1;

// 1) Naive Bayes hyper-parameters (model-only macro-F1 on val)
let best = null;
for (const alpha of [0.3, 0.5, 1, 2]) for (const maxFeatures of [2000, 3500, 5000]) {  // capped at 5000 to keep the browser bundle small
  const m = train(tr.items, {alpha, maxFeatures});
  const f = score(m, 'model');
  console.log(`  alpha=${alpha} features=${maxFeatures} → val macro-F1 ${f.toFixed(4)}`);
  if (!best || f > best.f) best = {alpha, maxFeatures, f, m};
}
// 2) Blend weight (hybrid macro-F1 on val)
const sweep = [];
for (const tau of [4, 6, 8, 99]) for (let w = 0; w <= 1.0001; w += 0.05) sweep.push({w: +w.toFixed(2), tau, f: score(best.m, 'hybrid', +w.toFixed(2), tau)});
const bw = sweep.reduce((a, b) => (b.f > a.f + 1e-9 ? b : a));
const rulesOnly = score(best.m, 'rules');
console.log(`best NB: alpha=${best.alpha}, features=${best.maxFeatures}; best blend w=${bw.w}, scope-guard tau=${bw.tau} (val macro-F1 ${bw.f.toFixed(4)}); rules-only ${rulesOnly.toFixed(4)}`);

// 3) Refit on train+val and export
const final = train([...tr.items, ...va.items], {alpha: best.alpha, maxFeatures: best.maxFeatures});
final.blend = {w: bw.w, tau: bw.tau};
final.trainedOn = {dataset: 'CUAD v1', split: 'train+val', contracts: 351 + 57, items: tr.items.length + va.items.length, date: new Date().toISOString().slice(0, 10)};
final.validation = {alpha: best.alpha, maxFeatures: best.maxFeatures, macroF1: {model: best.f, rules: rulesOnly, hybrid: bw.f}};
const js = `// Generated by scripts/ml/train-classifier.js — do not edit by hand.\n// Multinomial Naive Bayes trained on CUAD v1 (The Atticus Project, CC BY 4.0).\nexport default ${JSON.stringify(final)};\n`;
writeFileSync(join(ROOT, 'src', 'engine', 'ml', 'model.js'), js);
console.log(`wrote src/engine/ml/model.js (${(js.length / 1024).toFixed(0)} KB) in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
